drop policy if exists "Spot photos are publicly readable" on storage.objects;
create policy "Spot photos are publicly readable" on storage.objects
  for select to anon, authenticated using (bucket_id = 'spot-photos');
drop policy if exists "Users upload spot photos in own folder" on storage.objects;
create policy "Users upload spot photos in own folder" on storage.objects
  for insert to authenticated with check (
    bucket_id = 'spot-photos'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );

drop policy if exists "Approved verifications are public" on public.spot_verifications;
create policy "Approved verifications are public" on public.spot_verifications
  for select to anon, authenticated using (status = 'approved');
drop policy if exists "Users read own verification submissions" on public.spot_verifications;
create policy "Users read own verification submissions" on public.spot_verifications
  for select to authenticated using ((select auth.uid()) = user_id);
drop policy if exists "Users submit own pending verifications" on public.spot_verifications;
create policy "Users submit own pending verifications" on public.spot_verifications
  for insert to authenticated with check (
    (select auth.uid()) = user_id and status = 'pending'
  );
drop policy if exists "Admins manage verification submissions" on public.spot_verifications;
create policy "Admins manage verification submissions" on public.spot_verifications
  for all to authenticated
  using (exists (select 1 from public.app_admins where user_id = (select auth.uid())))
  with check (exists (select 1 from public.app_admins where user_id = (select auth.uid())));

grant select, insert on public.spot_verifications to authenticated;
